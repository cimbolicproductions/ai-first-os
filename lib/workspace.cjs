"use strict";

const fs = require("node:fs");
const path = require("node:path");

function toSimpleYaml(obj, indent = 0) {
  const pad = "  ".repeat(indent);
  if (obj === null || obj === undefined) return "null";
  if (typeof obj === "boolean" || typeof obj === "number") return String(obj);
  if (typeof obj === "string") return JSON.stringify(obj);
  if (Array.isArray(obj)) {
    if (!obj.length) return "[]";
    return "\n" + obj.map(item => {
      if (item && typeof item === "object") {
        const inner = toSimpleYaml(item, indent + 2).trimStart();
        return `${pad}  - ${inner}`;
      }
      return `${pad}  - ${toSimpleYaml(item, 0)}`;
    }).join("\n");
  }
  const entries = Object.entries(obj);
  if (!entries.length) return "{}";
  return entries.map(([k, v]) => {
    if (v && typeof v === "object" && !Array.isArray(v) && Object.keys(v).length > 0) {
      return `${pad}${k}:\n${toSimpleYaml(v, indent + 1)}`;
    }
    if (Array.isArray(v) && v.length > 0) {
      return `${pad}${k}:${toSimpleYaml(v, indent)}`;
    }
    return `${pad}${k}: ${toSimpleYaml(v, 0)}`;
  }).join("\n");
}

function loadManifest(workspaceRoot) {
  const root = path.resolve(workspaceRoot);
  for (const candidate of ["aios.json", "fleet.json"]) {
    const p = path.join(root, candidate);
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, "utf8"));
  }
  return null;
}

/** Writes the manifest under both its current and legacy names. */
function saveManifest(workspaceRoot, manifest) {
  const root = path.resolve(workspaceRoot);
  const yamlText = `# Generated by AI-first OS - stores secret NAMES only, never secret values\n${toSimpleYaml(manifest)}\n`;
  for (const jsonName of ["aios.json", "fleet.json"]) {
    fs.writeFileSync(path.join(root, jsonName), JSON.stringify(manifest, null, 2) + "\n", "utf8");
  }
  for (const yamlName of ["aios.yaml", "fleet.yaml"]) {
    fs.writeFileSync(path.join(root, yamlName), yamlText, "utf8");
  }
}

function getSetting(manifest, key) {
  return String(key)
    .split(".")
    .reduce((node, part) => (node && Object.hasOwn(node, part) ? node[part] : undefined), manifest);
}

function setSetting(manifest, key, value) {
  const parts = String(key).split(".");
  if (parts.some(p => ["__proto__", "constructor", "prototype"].includes(p))) {
    throw Object.assign(new Error("Invalid setting name."), { code: "INVALID_SETTING" });
  }
  let node = manifest;
  for (const part of parts.slice(0, -1)) {
    if (!Object.hasOwn(node, part) || typeof node[part] !== "object" || node[part] === null) node[part] = {};
    node = node[part];
  }
  node[parts.at(-1)] = value;
  return manifest;
}

module.exports = { toSimpleYaml, loadManifest, saveManifest, getSetting, setSetting };
