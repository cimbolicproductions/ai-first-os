"use strict";

const fs = require("node:fs");
const http = require("node:http");
const path = require("node:path");
const crypto = require("node:crypto");
const { createRelay, sha256Hex } = require("./relay-core.cjs");

const PHONE_DIR = path.join(__dirname, "..", "phone");
const STATIC_FILES = {
  "/": ["index.html", "text/html; charset=utf-8"],
  "/index.html": ["index.html", "text/html; charset=utf-8"],
  "/sw.js": ["sw.js", "text/javascript; charset=utf-8"],
  "/manifest.webmanifest": ["manifest.webmanifest", "application/manifest+json"],
  "/icon.svg": ["icon.svg", "image/svg+xml"],
};

/** JSON-file store for running the relay on the home machine or in tests. */
function createFileStore({ file, now = () => new Date() }) {
  function read() {
    if (!fs.existsSync(file)) return { next: 1, items: [], state: {} };
    return JSON.parse(fs.readFileSync(file, "utf8"));
  }
  function write(data) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.${crypto.randomUUID()}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(data), "utf8");
    fs.renameSync(tmp, file);
  }
  return {
    async add(kind, body) {
      const data = read();
      const item = { id: data.next++, kind, body, created_at: new Date(now()).toISOString(), consumed_at: null };
      data.items.push(item);
      write(data);
      return item;
    },
    async list(kinds) {
      return read().items.filter(i => !i.consumed_at && kinds.includes(i.kind));
    },
    async consume(ids) {
      const data = read();
      for (const item of data.items) if (ids.includes(item.id)) item.consumed_at = new Date(now()).toISOString();
      write(data);
    },
    async getState(key) {
      return read().state[key] ?? null;
    },
    async setState(key, value) {
      const data = read();
      data.state[key] = value;
      write(data);
    },
  };
}

function readBody(req, limit = 64 * 1024) {
  return new Promise((resolve, reject) => {
    let size = 0;
    const chunks = [];
    req.on("data", c => {
      size += c.length;
      if (size > limit) {
        reject(Object.assign(new Error("Too large"), { code: "TOO_LARGE" }));
        req.destroy();
      } else chunks.push(c);
    });
    req.on("end", () => {
      try {
        const text = Buffer.concat(chunks).toString("utf8");
        resolve(text ? JSON.parse(text) : {});
      } catch {
        resolve({});
      }
    });
    req.on("error", reject);
  });
}

function createRelayServer({ relay }) {
  return http.createServer(async (req, res) => {
    const pathname = req.url.split("?")[0];
    if (req.method === "GET" && Object.hasOwn(STATIC_FILES, pathname)) {
      const [name, type] = STATIC_FILES[pathname];
      res.writeHead(200, {
        "content-type": type,
        "cache-control": "no-store",
        "referrer-policy": "no-referrer",
      });
      res.end(fs.readFileSync(path.join(PHONE_DIR, name)));
      return;
    }
    try {
      const body = req.method === "POST" ? await readBody(req) : {};
      const out = await relay.handle({ method: req.method, path: pathname, headers: req.headers, body });
      res.writeHead(out.status, out.headers);
      res.end(out.body === null ? "" : JSON.stringify(out.body));
    } catch {
      res.writeHead(400, { "content-type": "application/json" });
      res.end(JSON.stringify({ ok: false, code: "BAD_REQUEST" }));
    }
  });
}

async function createLocalRelay({ file, phoneToken, homeToken, ring, now }) {
  return createRelay({
    store: createFileStore({ file, now }),
    phoneTokenHash: await sha256Hex(phoneToken),
    homeTokenHash: await sha256Hex(homeToken),
    ring,
    now,
  });
}

